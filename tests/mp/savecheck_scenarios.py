#!/usr/bin/env python3
"""ScenarioData of every galaxy in the cooked game data, as a C table for tests/mp/savecheck_test.cpp (owner: snapval).

Usage: python3 -I tests/mp/savecheck_scenarios.py [/data/cooked] > /tmp/savecheck_scenarios.inc

Reads StageData/<Galaxy>/<Galaxy>Scenario.arc (the cooked data is little-endian and uncompressed: RARC stored as 'CRAR', BCSV
fields swapped) and prints one line per galaxy:
    {"Name", hash16, starMask, scenarioMask, entries, powerStars, shownScenarios},
hash16 = (u16) MR::getHashCode(name); starMask = union of the PowerStarId column (a bit mask of the stars a scenario can give);
scenarioMask = scenario numbers 1..entries; powerStars = rows with PowerStarId != 0 (ScenarioData::getPowerStarNum);
shownScenarios = rows without IsHidden (ScenarioData::getScenarioNum, the SPN1 scenario count).
The game side (decomp/src/Game/MP/MpSaveGame.cpp, buildCheckLimits) derives the same masks from the loaded ScenarioData.
Never writes anything; reads the game data only.
"""
import os
import struct
import sys


def game_hash(name):
    h = 0
    for c in name.encode('ascii'):
        h = (h * 31 + c) & 0xFFFFFFFF
    return h


def find_bcsv(data, column):
    """The BCSV table in an archive that has `column` (located by its column hash; the header is validated)."""
    key = struct.pack('<I', game_hash(column))
    i = data.find(key)
    while i >= 0:
        for items in range(1, 64):
            for k in range(items):
                s = i - 16 - k * 12
                if s < 0:
                    continue
                n, it, off, es = struct.unpack_from('<iiiI', data, s)
                if it == items and off == 16 + items * 12 and 0 < n < 256 and 0 < es < 1024 and s + off + n * es <= len(data):
                    return data[s:]
        i = data.find(key, i + 1)
    return None


def bcsv_reader(d):
    n, items, off, es = struct.unpack_from('<iiiI', d, 0)
    cols = {}
    for i in range(items):
        h, mask, offs, shift, typ = struct.unpack_from('<IIHBB', d, 16 + i * 12)
        cols[h] = (mask, offs, shift, typ)

    def get(row, name):
        c = cols.get(game_hash(name))
        if c is None:
            return None
        mask, offs, shift, typ = c
        p = off + row * es + offs
        if typ in (0, 3):
            v = struct.unpack_from('<I', d, p)[0]
        elif typ == 4:
            v = struct.unpack_from('<H', d, p)[0]
        elif typ == 5:
            v = d[p]
        else:
            return None
        return (v & mask) >> shift
    return n, get


def main():
    cooked = sys.argv[1] if len(sys.argv) > 1 else '/data/cooked'
    root = os.path.join(cooked, 'files', 'StageData')
    rows = []
    for g in sorted(os.listdir(root)):
        path = os.path.join(root, g, g + 'Scenario.arc')
        if not os.path.exists(path):
            continue
        with open(path, 'rb') as f:
            d = find_bcsv(f.read(), 'PowerStarId')
        if d is None:
            raise SystemExit('no ScenarioData in ' + path)
        n, get = bcsv_reader(d)
        star = 0
        stars = 0
        scen = 0
        shown = 0
        for r in range(n):
            no = get(r, 'ScenarioNo')
            ps = get(r, 'PowerStarId') or 0
            star |= ps & 0xFF
            stars += 1 if ps else 0
            shown += 0 if get(r, 'IsHidden') else 1
            if no is not None and 1 <= no <= 8:
                scen |= 1 << (no - 1)
        rows.append((g, game_hash(g) & 0xFFFF, star, scen, n, stars, shown))
    print('// generated by tests/mp/savecheck_scenarios.py from the cooked game data (do not commit the output)')
    for g, h, star, scen, n, stars, shown in rows:
        print('{"%s", 0x%04X, 0x%02X, 0x%02X, %d, %d, %d},' % (g, h, star, scen, n, stars, shown))


if __name__ == '__main__':
    main()

// Generates platform/src/mp/mp_name_filter_data.inc (the game's copy of the name filter list) from server/src/core/name_filter.js, the one data file.
//   node scripts/gen-name-filter.mjs          write the .inc
//   node scripts/gen-name-filter.mjs --check  exit 1 when the .inc is stale (test/core/svcfix2-names.test.js does the same)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import list from '../src/core/name_filter.js';

export const OUT = fileURLToPath(new URL('../../platform/src/mp/mp_name_filter_data.inc', import.meta.url));
const lit = (w) => JSON.stringify(w);
export function render() {
  const arr = (name, words) => `static const char* const ${name}[] = {${words.map(lit).join(', ')}};\nstatic const int ${name}N = ${words.length};\n`;
  return [
    '// GENERATED by server/scripts/gen-name-filter.mjs from server/src/core/name_filter.js. Do not edit; do not print.\n',
    arr('kNfSubstring', list.substring), arr('kNfWord', list.word), arr('kNfExact', list.exact),
    arr('kNfReservedExact', list.reservedExact), arr('kNfReservedWord', list.reservedWord), arr('kNfReservedPrefix', list.reservedPrefix),
  ].join('');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (cur !== text) { console.error('mp_name_filter_data.inc is stale: run node server/scripts/gen-name-filter.mjs'); process.exit(1); }
  } else writeFileSync(OUT, text);
}

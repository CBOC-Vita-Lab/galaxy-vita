#!/usr/bin/env python3
"""Write tools/pgo/vita_env.sh from the defaults vita/vgx-game/entry.cpp sets (setenv(name, value, 0) and the
`for (const char* name : {...}) setenv(name, "v", 0)` loops), so that the profile is recorded with the console's release
environment.  Run it again whenever entry.cpp's defaults change:

    python3 -I tools/pgo/gen_vita_env.py > tools/pgo/vita_env.sh

Added by hand: the variables the Vita sets by itself (not in entry.cpp).

Then the Settings start-up layer (pgotool31, 18 Nov 2026): on the console port_settings_startup (vita/vgx-game/settings_runtime.cpp)
runs port::settings::ApplyStartup after these defaults, and the picture mode's fan-out (the per-mode key table, the Performance
umbrella levels, GXV_HRW=5, the governors ...) rewrites about 60 of them. The harness has no Settings start-up, so this script
builds tools/pgo/settings_env.cpp on the host (clang++, the settings sources of this tree) and runs it on a fresh console's state
(no env.txt, no settings file) to get the environment the console really plays with.

    --picture-mode 60   Performance ("Smooth Motion", the release default)      --picture-mode 30   Quality ("Full Detail")
    --entry-only        entry.cpp's defaults alone (the file before 18 Nov)"""
import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
ap.add_argument("--picture-mode", choices=("60", "30"), default="60")
ap.add_argument("--entry-only", action="store_true")
args = ap.parse_args()

root = Path(__file__).resolve().parents[2]
lines = (root / "vita/vgx-game/entry.cpp").read_text().split("\n")
start = next(i for i, l in enumerate(lines) if 'LoadEnvFile(SMG_DATA "/env.txt")' in l)
end = next(i for i, l in enumerate(lines) if i > start and "PETARI_THP_BENCH_HZ" in l)
text = "\n".join(re.sub(r"(?<!:)//.*$", "", l) for l in lines[start:end])
env, order = {}, []
def put(name, value):
    if name not in env:
        order.append(name)
    env[name] = value
for m in re.finditer(r'for \(const char\* name : \{([^}]*)\}\)\s*(?:\{\s*)?setenv\(name, "([^"]*)", 0\)', text):
    for name in re.findall(r'"([^"]+)"', m.group(1)):
        put(name, m.group(2))
for m in re.finditer(r'setenv\("([A-Z0-9_]+)", "([^"]*)", 0\)', text):
    put(m.group(1), m.group(2))
for name, value in (("GXV_SPLIT", "1"), ("GXV_VITA", "1"), ("GXV_STATIC_USAGE", "dynamic")):   # chosen by the console itself
    put(name, value)
layer = "entry.cpp's defaults only (--entry-only): no Settings start-up layer"
if not args.entry_only:
    srcs = ["tools/pgo/settings_env.cpp", "platform/src/settings/settings_launch.cpp", "platform/src/settings/player_settings.cpp",
            "platform/src/input/control_bindings.cpp"]
    with tempfile.TemporaryDirectory() as tmp:
        exe = os.path.join(tmp, "settings_env")
        cxx = os.environ.get("HOST_CXX", "clang++")
        link_extra = ["-Wl,-undefined,dynamic_lookup"] if sys.platform == "darwin" else []
        subprocess.run([cxx, "-std=c++20", "-O0", "-w", "-I", str(root / "platform/include"), "-DPORT_PLATFORM_CODE=1",
                        *[str(root / f) for f in srcs], *link_extra, "-o", exe], check=True)
        run = subprocess.run([exe, args.picture_mode], env={n: env[n] for n in order}, check=True, capture_output=True, text=True)
    after = dict(l.split("=", 1) for l in run.stdout.splitlines() if "=" in l)
    changed = sorted(n for n in order if n in after and after[n] != env[n])
    gone = sorted(n for n in order if n not in after)
    for n in gone:   # (the start-up never unsets a key today; a key it removed would be dropped here)
        order.remove(n)
        del env[n]
    added = sorted(n for n in after if n not in env)
    for n in changed + added:
        put(n, after[n])
    layer = (f"the Settings start-up layer: {run.stderr.strip()}; {len(changed)} changed, {len(added)} added" +
             (f", {len(gone)} removed" if gone else ""))
bad = [n for n in order if re.search(r"\s", env[n])]
if bad:
    sys.exit(f"gen_vita_env.py: a value with white space cannot go into VITA_ENV: {bad}")
print("# The environment the Vita release defaults set (vita/vgx-game/entry.cpp), plus the choices the console makes by itself: the")
print("# front-end split on, the Vita capabilities, static geometry in main memory.  GENERATED by tools/pgo/gen_vita_env.py: do not edit,")
print("# run the generator again when entry.cpp's defaults change.  Source it and pass \"$VITA_ENV\" as EXTRA_ENV to tools/pgo/run_route.sh,")
print("# so that the renderer runs the same code paths while a profile is recorded as it does on the console.")
print(f"# Then {layer}.")
print('VITA_ENV="' + " \\\n".join(" ".join(f"{n}={env[n]}" for n in order[i:i + 6]) for i in range(0, len(order), 6)) + '"')

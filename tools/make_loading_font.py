#!/usr/bin/env python3
"""Pre-renders the text of the PS Vita loading screen (platform/vgx/vita/loading_screen.h) into
platform/vgx/vita/loading_font.inc: 8-bit coverage bitmaps, so the console needs no font library.

  tools/make_loading_font.py [out.inc]

Fonts: DejaVu Sans (Bold / Regular), whose license (Bitstream Vera, public domain additions) allows
this. The title line is rendered whole, with a version dilated by a few pixels for its outline.
"""
import sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter

BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
REG = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
out = sys.argv[1] if len(sys.argv) > 1 else "platform/vgx/vita/loading_font.inc"

def emit_array(name, data, per_line=32):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append(",".join(str(b) for b in data[i:i + per_line]))
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (name, len(data), ",\n".join(lines))

def font_atlas(tag, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = []
    data = bytearray()
    for code in range(32, 127):
        ch = chr(code)
        adv = font.getlength(ch)
        img = Image.new("L", (int(adv) + size, height + 4), 0)
        ImageDraw.Draw(img).text((2, 0), ch, font=font, fill=255)
        bbox = img.getbbox()
        if bbox is None:
            glyphs.append((0, 0, 0, 0, int(round(adv)), len(data)))
            continue
        x0, y0, x1, y1 = bbox
        crop = img.crop(bbox)
        glyphs.append((x1 - x0, y1 - y0, x0 - 2, y0, int(round(adv)), len(data)))
        data += crop.tobytes()
    s = emit_array("k%sData" % tag, data)
    s += "static const LoadingGlyph k%sGlyphs[95] = {\n" % tag
    s += ",\n".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs)
    s += "\n};\n"
    s += "static const int k%sAscent = %d, k%sHeight = %d;\n" % (tag, ascent, tag, height)
    return s, len(data)

def title_image(text, size, pad):
    font = ImageFont.truetype(BOLD, size)
    spacing = 3
    width = int(sum(font.getlength(c) for c in text)) + spacing * (len(text) - 1)
    ascent, descent = font.getmetrics()
    img = Image.new("L", (width + 2 * pad, ascent + descent + 2 * pad), 0)
    d = ImageDraw.Draw(img)
    x = pad
    for c in text:
        d.text((x, pad), c, font=font, fill=255)
        x += font.getlength(c) + spacing
    outline = img.filter(ImageFilter.MaxFilter(7))  # 3 px all round
    outline = outline.filter(ImageFilter.GaussianBlur(0.7))
    return img, outline

parts = []
parts.append("// Generated by tools/make_loading_font.py from DejaVu Sans (Bitstream Vera license). Do not edit.\n"
             "// LoadingGlyph: width, height, x offset, y offset (from the line's top), advance, offset in the data.\n")
total = 0
for tag, path, size in (("Med", BOLD, 22), ("Small", REG, 14)):
    s, n = font_atlas(tag, path, size)
    parts.append(s)
    total += n
title, outline = title_image("SUPER MARIO GALAXY", 54, 5)
parts.append(emit_array("kTitleAlpha", title.tobytes()))
parts.append(emit_array("kTitleOutline", outline.tobytes()))
parts.append("static const int kTitleW = %d, kTitleH = %d;\n" % title.size)
total += 2 * title.size[0] * title.size[1]
open(out, "w").write("".join(parts))
print("%s: %d bytes of bitmaps, title %dx%d" % (out, total, *title.size))
